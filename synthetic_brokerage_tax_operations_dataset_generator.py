    accounts_c = accounts.copy(deep=True)
    transactions_c = transactions.copy(deep=True)
    cost_basis_c = cost_basis.copy(deep=True)
    tax_forms_c = tax_forms.copy(deep=True)
    withholding_c = withholding.copy(deep=True)

