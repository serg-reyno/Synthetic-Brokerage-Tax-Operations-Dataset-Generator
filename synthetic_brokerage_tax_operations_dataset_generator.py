    transactions_c.to_csv(os.path.join(CORRUPTED_DIR, "transactions.csv"), index=False)
    cost_basis_c.to_csv(os.path.join(CORRUPTED_DIR, "cost_basis.csv"), index=False)
    tax_forms_c.to_csv(os.path.join(CORRUPTED_DIR, "tax_forms.csv"), index=False)
    withholding_c.to_csv(os.path.join(CORRUPTED_DIR, "withholding.csv"), index=False)
    error_log_df.to_csv(os.path.join(CORRUPTED_DIR, "error_log.csv"), index=False)

    # -----------------------------------------------------------------
    # Phase 2 summary
    # -----------------------------------------------------------------
    print("\n" + "=" * 78)
    print("PHASE 2 ERROR INJECTION SUMMARY")
    print("=" * 78)
    print(f"Total errors injected: {len(error_log_df)}")

    print("\nErrors by error_type:")
    for etype, cnt in error_log_df["error_type"].value_counts().sort_index().items():
        print(f"  {etype}: {cnt}")

    print("\nErrors by dataset:")
    for ds, cnt in error_log_df["dataset"].value_counts().sort_index().items():
        print(f"  {ds}: {cnt}")

    print("\nErrors by severity:")
    for sev, cnt in error_log_df["severity"].value_counts().reindex(["LOW", "MEDIUM", "HIGH"]).dropna().items():
        print(f"  {sev}: {int(cnt)}")

    unique_accounts_affected = error_log_df.loc[error_log_df["account_id"] != "", "account_id"].nunique()
    print(f"\nUnique accounts affected: {unique_accounts_affected}")

    # Structural checks (should still pass)
    structural_ok = run_structural_checks(accounts_c, transactions_c, cost_basis_c, tax_forms_c, withholding_c)

    # Selected Phase 1 controls (should now fail, confirming corruption worked)
    run_expected_failures(accounts_c, transactions_c, cost_basis_c, tax_forms_c, withholding_c)

    print("\n" + "=" * 78)
    if structural_ok:
        print("Structural integrity preserved (PKs unique, FKs valid, dates parseable) - as expected.")
    else:
        print("WARNING: a structural check failed - this should NOT happen from these error "
              "categories. Review run_structural_checks() output above.")
    print(f"\nCorrupted datasets and error_log.csv written to {CORRUPTED_DIR}/")
    print("Clean datasets in data/clean/ were not modified.")
    print("=" * 78)


