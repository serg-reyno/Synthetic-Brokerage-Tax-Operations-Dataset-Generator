_error_log_rows = []
_error_counter = 1


def log_error(error_type, dataset, record_identifier, account_id, transaction_id,
              original_value, corrupted_value, field_changed, description,
              severity, expected_detection_method):
    """Appends one row to the ground-truth error log."""
    global _error_counter
    error_id = f"ERR{_error_counter:04d}"
    _error_counter += 1
    _error_log_rows.append({
        "error_id": error_id,
        "error_type": error_type,
        "dataset": dataset,
        "record_identifier": record_identifier,
        "account_id": account_id if account_id is not None else "",
        "transaction_id": transaction_id if transaction_id is not None else "",
        "original_value": original_value,
        "corrupted_value": corrupted_value,
        "field_changed": field_changed,
        "description": description,
        "severity": severity,
        "expected_detection_method": expected_detection_method,
    })
    return error_id


