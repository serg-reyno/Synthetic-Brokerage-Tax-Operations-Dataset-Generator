    inject_w9_errors(accounts_c)
    inject_w8_errors(accounts_c)

    # Withholding errors
    withholding_c = inject_backup_withholding_errors(accounts_c, withholding_c)
    withholding_c = inject_nra_withholding_errors(withholding_c)

    # Cross-dataset reporting-relationship breaks (run last: reads several
    # already-corrupted datasets to pick disjoint targets)
    tax_forms_c = inject_reporting_relationship_breaks(accounts_c, transactions_c, cost_basis_c, tax_forms_c)

    # -----------------------------------------------------------------
    # Build and export the error log (ground truth - not used for detection)
    # -----------------------------------------------------------------
    error_log_df = pd.DataFrame(_error_log_rows)

    # -----------------------------------------------------------------
    # Export corrupted datasets
    # -----------------------------------------------------------------
