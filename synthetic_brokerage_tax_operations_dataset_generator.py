# 2. ERROR INJECTION FUNCTIONS (one per category)
# ---------------------------------------------------------------------------
# "used_*" sets track which primary keys have already been corrupted so that,
# per the assignment's instructions, unrelated errors are not stacked onto
# the same record unless it's a natural pairing.
used_basis_ids = set()
used_form_ids = set()
used_withholding_ids = set()
used_accounts_w9 = set()
used_accounts_w8 = set()


def pick_rows(df, mask, n, exclude_ids=None, id_col=None):
    """Helper: sample up to n row-indices from df matching mask, optionally
    excluding a set of already-used primary-key values."""
    candidates = df[mask]
    if exclude_ids is not None and id_col is not None:
        candidates = candidates[~candidates[id_col].isin(exclude_ids)]
    n = min(n, len(candidates))
    if n == 0:
        return candidates.iloc[0:0]
    idx = NP_RNG.choice(candidates.index.values, size=n, replace=False)
    return df.loc[idx]


# --- 1. MISSING COST BASIS --------------------------------------------------
def inject_missing_cost_basis(cost_basis_c):
    n = RNG.randint(8, 12)
    rows = pick_rows(cost_basis_c, cost_basis_c["cost_basis"].notna(), n,
                      used_basis_ids, "basis_record_id")
    for _, row in rows.iterrows():
        original = cost_basis_c.at[row.name, "cost_basis"]
        cost_basis_c.at[row.name, "cost_basis"] = np.nan
        used_basis_ids.add(row["basis_record_id"])
        log_error(
            "MISSING_COST_BASIS", "cost_basis.csv", row["basis_record_id"],
            row["account_id"], row["transaction_id"],
            original, "", "cost_basis",
            "Cost basis field was nulled out on an otherwise valid disposed lot, "
            "simulating a feed/booking gap that would block accurate gain/loss reporting.",
            "MEDIUM", "NULL_CHECK",
        )


# --- 2. INCORRECT COST BASIS ------------------------------------------------
def inject_incorrect_cost_basis(cost_basis_c):
    n = RNG.randint(5, 8)
    rows = pick_rows(cost_basis_c, cost_basis_c["cost_basis"].notna(), n,
                      used_basis_ids, "basis_record_id")
    for _, row in rows.iterrows():
        original = cost_basis_c.at[row.name, "cost_basis"]
        adjustment_kind = RNG.choice(["pct_up", "pct_down", "fixed"])
        if adjustment_kind == "pct_up":
            new_value = round(original * 1.10, 2)
        elif adjustment_kind == "pct_down":
            new_value = round(original * 0.90, 2)
        else:
            new_value = round(original + RNG.choice([100, 250, 500]), 2)
        cost_basis_c.at[row.name, "cost_basis"] = new_value
        used_basis_ids.add(row["basis_record_id"])
        log_error(
            "INCORRECT_COST_BASIS", "cost_basis.csv", row["basis_record_id"],
            row["account_id"], row["transaction_id"],
            original, new_value, "cost_basis",
            "Cost basis amount was altered from its correct lot value, simulating a "
            "corporate-action or manual cost-basis-adjustment booking error.",
            "MEDIUM", "ARITHMETIC_RECONCILIATION",
        )


# --- 3. INCORRECT 1099-B PROCEEDS ------------------------------------------
