def ensure_clean_dir():
    """Makes sure data/clean/ is populated. If it's missing but the original
    flat data/ layout from the Phase 1 script exists, copy (never move) the
    files into data/clean/ so this script's contract ("read from
    data/clean/") is satisfied without touching the Phase 1 script."""
    have_clean = all(os.path.exists(os.path.join(CLEAN_DIR, f)) for f in REQUIRED_FILES)
    if have_clean:
        return
    have_legacy = all(os.path.exists(os.path.join(LEGACY_DIR, f)) for f in REQUIRED_FILES)
    if have_legacy:
        os.makedirs(CLEAN_DIR, exist_ok=True)
        for f in REQUIRED_FILES:
            shutil.copy(os.path.join(LEGACY_DIR, f), os.path.join(CLEAN_DIR, f))
        print(f"Note: populated {CLEAN_DIR}/ by copying Phase 1 output found in {LEGACY_DIR}/ "
              f"(originals left untouched).")
        return
    raise FileNotFoundError(
        f"Could not find the five Phase 1 CSVs in either {CLEAN_DIR}/ or {LEGACY_DIR}/. "
        f"Run the Phase 1 generator first."
    )


